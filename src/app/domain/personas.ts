/** Builds a 24-month history from a compact spec like "OK*20 M30 OK*3". */
export function h(spec: string): MonthStatus[] {
  const out: MonthStatus[] = [];
  for (const part of spec.trim().split(/\s+/)) {
    const [s, n] = part.split('*');
    for (let i = 0; i < Number(n ?? 1); i++) out.push(s as MonthStatus);
  }
  if (out.length !== 24) throw new Error(`history must have 24 months, got ${out.length}`);
  return out;
}

